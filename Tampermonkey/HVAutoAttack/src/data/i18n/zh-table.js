/**
 * 简 → 繁 反向映射表。由 T2S 反转构建(简体一对多时保留首个), 再用 S2T_OVERRIDE
 * 强制锁定常用形。逻辑层 toTraditional 直接消费本表。
 * 注意: 此为次要路径, 简→繁存在一对多歧义, 仅取最常用形, 个别字会不准(见文件头)。
 * @type {Record<string,string>}
 */
export const S2T = (() => {
  /** @type {Record<string,string>} */
  const m = {};
  for (const trad in T2S) {
    const simp = T2S[trad];
    if (!(simp in m)) m[simp] = trad; // 一对多时保留首个, override 稍后强制锁定常用形
  }
  for (const simp in S2T_OVERRIDE) m[simp] = S2T_OVERRIDE[simp];
  return m;
})();
