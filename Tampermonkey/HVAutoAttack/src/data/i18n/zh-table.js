  // 以下四字一对多, 但 HV 语境(装备/战斗/属性)更常用"取自身"义, 显式锁定为不转, 避免误转:
  板: "板", // 面板/木板=板 vs 老闆=闆(异形); 取 板。
  表: "表", // 属性表/数值表/表面=表 vs 手表/钟表=錶; HV 多为"属性表", 取 表。
